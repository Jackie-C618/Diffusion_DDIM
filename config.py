"""
================================================================================
config.py —— 超参数

config.py（常量）
    ├──→ schedule.py  用 T / BETA_START / BETA_END / DEVICE
    ├──→ model.py     用 BASE_CHANNELS / DEPTH / ATTN_AT / TIME_EMB_DIM
    ├──→ dataset.py   用 BATCH_SIZE / DATA_DIR / NORM_* / IMAGE_SIZE / CHANNELS
    ├──→ diffusion.py 用 T / DEVICE
    ├──→ ddim.py      用 T / DEVICE
    ├──→ train.py     用 T / LR / EPOCHS / CKPT / DEVICE / SEED
    └──→ sample*.py   用 CKPT / SAMPLES_PNG / DEVICE / SEED
================================================================================

【目的】
    扩散模型里超参比较多
    例如 T 同时决定 schedule 的长度和训练时 t 的采样上限，
    若两处写了不同数字，q_sample 的 gather 会直接索引越界。
    集中在一处，改一个数字就能保证全链路同步。
    可以在任何模块里 `import config; print(config.T)` 查看某个值。

【DDIM相关的重要提醒】
    T = 1000 是「训练时的扩散总步数」，它决定 schedule 表的长度；
    DDIM 采样时用多少步由 ddim.py 的 ddim_steps 单独控制（默认 50）。
    两者是不同概念，不要为了「加速采样」去改 T 。 
    改 T 会让已训好的 ckpt 直接失效（schedule 变了，模型学到的去噪分布对不上）。
 
================================================================================
"""
import torch                                        # 只用它的 cuda.is_available() 来自动选设备

DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

# ----------------------------------------------------------------------------
# 第 0 步：数据集相关
# ----------------------------------------------------------------------------
BATCH_SIZE = 128    # 一次训练喂给网络多少张图。显存不够就调小（64 / 32）；
                    # 注意它只影响训练速度，不影响数学公式。
IMAGE_SIZE = 28     # MNIST 每张图是 28×28 像素，这里主要给自检断言用
CHANNELS = 1        # 单通道灰度图。若是 CIFAR-10 彩色图要改成 3，
                    # 同时 model.py 的 in_ch 也要跟着改。
# 下面两个值配合 transforms.Normalize 使用，把像素从 [0,1] 线性映射到 [-1,1]：
#     (x - 0.5) / 0.5 = 2x - 1
# 为什么必须映射到 [-1,1]：DDPM/DDIM 把 x_0 看作 [-1,1] 上的连续量，
# 而采样起点 x_T ~ N(0,I) 的均值是 0。
# 两边都以 0 为中心，前向加噪才是一条无偏移的插值；出图时再用 (x+1)/2 反变换回 [0,1] 显示。
NORM_MEAN = 0.5
NORM_STD = 0.5

# ----------------------------------------------------------------------------
# 第 1 步：扩散过程（前向加噪的「配方」）
# ----------------------------------------------------------------------------
T = 1000            # 扩散总步数，也是 schedule 张量的长度、训练时 t 的上限。
                    # 论文用 1000；改小能加速训练，但要重训。
BETA_START = 1e-4   # 加噪起点：t=0 附近每步只加极少量噪声。如果设定为0，其一这对数据几乎无扰动，其二在反向去噪时须跳过分母为0的一步
BETA_END = 0.02     # 加噪终点：t≈T 时每步加较多噪声
                    # 这两个值在 schedule.py 里被 linspace 拉成 T 个数。

# ----------------------------------------------------------------------------
# 第 3 步：U-Net 结构
# ----------------------------------------------------------------------------
BASE_CHANNELS = 64  # 第一层卷积的输出通道数，之后每下采样一次翻倍（64→128→256）。
                    # 调大模型性能更好但运行会更慢；调小便于快速验证。
DEPTH = 2           # 下采样次数。28 是偶数，下采样 2 次正好 28→14→7，上采样原路返回最稳。
ATTN_AT = 1         # >=0 表示在 bottleneck 加自注意力；-1 表示不加。
                    # 这里只用一个开关，具体放哪一档由 model.py 的 MidBlock 决定。
TIME_EMB_DIM = 256  # 时间步 t 经正弦编码后的向量维度，也是各层 MLP 的宽度。
                    # 这个向量会通过 FiLM 注入每一个 ResidualBlock。

# ----------------------------------------------------------------------------
# 第 5 步：训练
# ----------------------------------------------------------------------------
LR = 2e-4           # Adam 学习率。DDPM 论文用 1e-4。
EPOCHS = 20         # 训练轮数
SEED = 42           # 随机种子：固定它才能复现同一批噪声、同一张生成图。
                    # train.py / sample.py / sample_ddim.py 都会 manual_seed

# ----------------------------------------------------------------------------
# 路径（全部是相对运行时的工作目录的路径，所以 cd 到本文件夹再运行）
# ----------------------------------------------------------------------------
DATA_DIR = "data"           # torchvision 把 MNIST 下载到这里
CKPT = "ckpt_last.pt"       # 训练保存 / 采样加载的模型权重（state_dict）
SAMPLES_PNG = "samples.png" # DDPM 采样器的输出图名
